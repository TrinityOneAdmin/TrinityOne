#!/usr/bin/env bash
# build-finance-desktop.sh [out] — the bundled frontend of the TrinityOne Finance DESKTOP program (Tauri, Win/Mac/Linux).
#   default out: finance-app/desktop/src-tauri/dist   (tauri.conf.json build.frontendDist; gitignored)
#
# T1Finance desktop plan (TrinityOne-internal/PLAN-T1FINANCE-DESKTOP-2026-11-17.md) §2, step 1. The program BUNDLES
# finance.html's files (D1): offline, code fixed at build, our CSP, relays = the canonical pool exactly like the
# Android finance app (src/steward.src.js _packagedOrigin — tauri://localhost and https://tauri.localhost).
#
# Steps:
#   1. scripts/collect-app-page.sh finance.html — the SAME page-derived copy the APKs use (every local reference
#      copied or the build FAILS, runtime Babel dropped, JSX pre-transpiled).
#   2. drop sw-register.js: a service worker has nothing to cache in a program whose files are on disk, and one
#      registered under tauri://localhost would only serve stale screens after an upgrade.
#   3. generate desktop-build.js — window.TRINITY_BUILD = { app: 'finance-desktop', version, sha } — loaded as an
#      EXTERNAL script (the strict CSP allows no inline one) immediately before finance-mode.js. It is for display
#      and the update banner's version compare ONLY; nothing may make a relay or permission decision from it.
# Run: bash scripts/build-finance-desktop.sh [out]
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="${1:-finance-app/desktop/src-tauri/dist}"
CONF="finance-app/desktop/src-tauri/tauri.conf.json"

VERSION=$(node -p "require('./$CONF').version")
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?$ ]] || { echo "✖ $CONF version '$VERSION' is not semver" >&2; exit 1; }
SHA=$(git rev-parse --short=12 HEAD 2>/dev/null || echo unknown)

# the DEFAULT output is a fixed, gitignored build folder (one built before collect-app-page.sh wrote its marker would
# otherwise be refused); any other <out> is checked by collect-app-page.sh before it deletes anything.
[ "$OUT" = "finance-app/desktop/src-tauri/dist" ] && rm -rf "$OUT"
bash scripts/collect-app-page.sh finance.html "$OUT"

# 2. no service worker
rm -f "$OUT/sw-register.js"
# (index.html is edited with node, never `sed -i` — GNU-only; this script runs on a Mac for the Mac build)
node -e '
const fs = require("fs"), f = process.argv[1];
fs.writeFileSync(f, fs.readFileSync(f, "utf8").split("\n").filter((l) => !l.includes("<script src=\"sw-register.js\"></script>")).join("\n"));
' "$OUT/index.html"
if grep -q 'sw-register' "$OUT/index.html"; then echo "✖ $OUT/index.html still names sw-register.js" >&2; exit 1; fi

# 3. the build stamp, before finance-mode.js
printf "// Generated by scripts/build-finance-desktop.sh — the desktop program's build stamp. Display/compare only:\n// never read for a relay or permission decision.\nwindow.TRINITY_BUILD = Object.freeze(%s);\n" \
  "$(node -e 'process.stdout.write(JSON.stringify({ app: "finance-desktop", version: process.argv[1], sha: process.argv[2] }))' "$VERSION" "$SHA")" > "$OUT/desktop-build.js"
n=$(grep -c '<script src="finance-mode\.js"></script>' "$OUT/index.html" || true)
[ "$n" = "1" ] || { echo "✖ expected exactly one <script src=\"finance-mode.js\"> in finance.html, found $n" >&2; exit 1; }
node -e '
const fs = require("fs"), f = process.argv[1], tag = "<script src=\"finance-mode.js\"></script>";
fs.writeFileSync(f, fs.readFileSync(f, "utf8").replace(tag, "<script src=\"desktop-build.js\"></script>\n" + tag));
' "$OUT/index.html"

echo "→ $OUT  (TrinityOne Finance desktop $VERSION @ $SHA, $(du -sh "$OUT" | cut -f1))"
