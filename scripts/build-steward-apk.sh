#!/usr/bin/env bash
# Build the standalone Steward APK (trinityone-steward.apk): the steward console
# (steward.html + stew-*.jsx) wrapped as its OWN Android app (com.trinityone.steward), so a steward
# can create + manage a church on a phone, talking straight to the relays — a host-independent
# fallback if the web console is blocked. Re-uses the shared android/ project via a temporary
# applicationId / app-name / webDir swap, ALWAYS reverted on exit (the member project is restored).
#
# ONE SCRIPT, TWO CONSOLE APPS (T1Finance, 2026-11-17):
#   bash scripts/build-steward-apk.sh            the Steward console, exactly as before (release.sh calls it so)
#   bash scripts/build-steward-apk.sh finance    "TrinityOne Finance" (com.trinityone.finance) from finance.html
#                                                -> trinityone-finance.apk; scripts/build-finance-apk.sh is this.
# Same steps for both: the page's every local reference copied or the build FAILS, JSX pre-transpiled, the
# member-only manifest blocks stripped, the release-sign + debuggable refusal, and the member project put back.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$(pwd)"
APP="${1:-steward}"
case "$APP" in
  steward) APP_ID="com.trinityone.steward"; APP_NAME="TrinityOne Console"; PAGE="steward.html"; ICONS="assets/steward-icons"; OUT="trinityone-steward.apk" ;;
  finance) APP_ID="com.trinityone.finance"; APP_NAME="TrinityOne Finance"; PAGE="finance.html"; ICONS="assets/finance-icons";  OUT="trinityone-finance.apk" ;;
  *) echo "usage: $0 [steward|finance]" >&2; exit 2 ;;
esac
WWW="$ROOT/www"
GRADLE="android/app/build.gradle"
STRINGS="android/app/src/main/res/values/strings.xml"
RES="android/app/src/main/res"
DENS="mdpi hdpi xhdpi xxhdpi xxxhdpi"
ICON_BAK="$(mktemp -d)"

# whatever happens, put the member project back (app id, name, icon, and the member www/).
# EITHER console's id and name go back, whichever this run is: a build of the OTHER variant killed hard (no trap)
# would otherwise leave its id in build.gradle, and the next build would ship under the wrong app id.
restore() {
  bash scripts/manifest-member-only.sh restore 2>/dev/null || true   # the member-only intent-filter(s) come back
  sed -i -e 's/applicationId "com.trinityone.steward"/applicationId "com.trinityone.app"/' \
         -e 's/applicationId "com.trinityone.finance"/applicationId "com.trinityone.app"/' "$GRADLE" 2>/dev/null || true
  sed -i -e 's#<string name="app_name">TrinityOne Console</string>#<string name="app_name">TrinityOne</string>#' \
         -e 's#<string name="app_name">TrinityOne Finance</string>#<string name="app_name">TrinityOne</string>#' "$STRINGS" 2>/dev/null || true
  sed -i -e 's#<string name="title_activity_main">TrinityOne Console</string>#<string name="title_activity_main">TrinityOne</string>#' \
         -e 's#<string name="title_activity_main">TrinityOne Finance</string>#<string name="title_activity_main">TrinityOne</string>#' "$STRINGS" 2>/dev/null || true
  for d in $DENS; do cp "$ICON_BAK/mipmap-$d/"*.png "$RES/mipmap-$d/" 2>/dev/null || true; done
  rm -rf "$ICON_BAK"
  echo "restoring member www/ + project…"
  bash scripts/sync-web.sh >/dev/null 2>&1 || true
}
trap restore EXIT

source scripts/android-env.sh

# swap to the console's (midnight + keeper-ring) launcher icon — same adaptive XML, swapped mipmap PNGs.
# Back up the member icons first (android/ is gitignored = disk-only) and restore them on exit.
# Steward + finance icons are generated by: node scripts/make-icons.mjs  (committed under assets/<app>-icons/).
if [ -d "$ICONS" ]; then
  echo "swapping in the $APP icon…"
  for d in $DENS; do
    mkdir -p "$ICON_BAK/mipmap-$d"
    cp "$RES/mipmap-$d/"ic_launcher*.png "$ICON_BAK/mipmap-$d/" 2>/dev/null || true
    cp "$ICONS"/mipmap-$d/*.png "$RES/mipmap-$d/"
  done
fi

# 1. console webDir — only what the page ($PAGE) references; the page becomes index.html
echo "building $APP webDir…"
# The page is the source of truth: scripts/collect-app-page.sh copies every local file $PAGE references (and FAILS
# on a missing one — the 2026-08-17 dead-console story is told there), drops runtime Babel and pre-transpiles the JSX.
# The same script builds the desktop finance program's bundle (scripts/build-finance-desktop.sh).
# www/ is this script's fixed folder (the member build, scripts/sync-web.sh, writes it too, without
# collect-app-page.sh's marker), so clear it here; collect-app-page.sh refuses a non-empty folder it did not write.
rm -rf "$WWW"
bash scripts/collect-app-page.sh "$PAGE" "$WWW"

# 2a. take the MEMBER-ONLY intent-filter(s) out of the manifest (e.g. "Open with TrinityOne" for a Bible file): the
# Console has no Library and no listener, so it must not be offered for every zip on the phone. The block sits
# between BEGIN/END markers; restore() above puts the file back byte for byte (scripts/manifest-member-only.sh).
bash scripts/manifest-member-only.sh strip

# 2. swap to the console app's identity (separate install from the member app, and from each other)
sed -i "s/applicationId \"com.trinityone.app\"/applicationId \"$APP_ID\"/" "$GRADLE"
sed -i "s#<string name=\"app_name\">TrinityOne</string>#<string name=\"app_name\">$APP_NAME</string>#" "$STRINGS"
sed -i "s#<string name=\"title_activity_main\">TrinityOne</string>#<string name=\"title_activity_main\">$APP_NAME</string>#" "$STRINGS"
# and REFUSE if the swap did not land: a project left in another app's identity (a hard-killed build) would make
# the sed above a no-op and ship this app under the wrong id — installing over the other app on every phone.
grep -q "applicationId \"$APP_ID\"" "$GRADLE" || { echo "✖ $GRADLE does not carry applicationId \"$APP_ID\" after the swap — refusing to build" >&2; exit 1; }
grep -q "<string name=\"app_name\">$APP_NAME</string>" "$STRINGS" || { echo "✖ $STRINGS does not carry the app name \"$APP_NAME\" after the swap — refusing to build" >&2; exit 1; }

# 3. copy webDir into the native project + build
#
# ⚠ PILOT-DEFERRED: DEBUG-signed on purpose (owner's call, 2026-07-22). 8f5090e switched this to
# assembleRelease (release cert, no android:debuggable) as a SECURITY fix — correct for go-live, but it was
# part of the go-live hardening the owner had explicitly deferred until pilot start, and it slipped through
# the same-batch revert that put webContentsDebuggingEnabled back ON (9c74d61). Release-signing mid-pilot-prep
# breaks the test phone's in-place update path (a different key can't upgrade the installed app), so this is
# reverted to the debug cert the phone already trusts. No real congregation is on anything yet, so the
# debug-cert / debuggable blast radius is zero — which is exactly why it was deferred.
#
# ‼ BEFORE ANY REAL GO-LIVE: build with TRINITY_DEBUG=0 (handled just below — disables WebView debugging on
#   the steward APK too) AND switch back to the release build below. It is the correct shipping posture:
#     [ -f android/app/keystore.properties ] || { echo "ERROR: keystore.properties missing" >&2; exit 1; }
#     ( cd android && ./gradlew assembleRelease -q )
#     cp android/app/build/outputs/apk/release/app-release.apk trinityone-steward.apk
#     aapt2 dump badging trinityone-steward.apk | grep -q application-debuggable && { echo "DEBUGGABLE — refusing"; exit 1; }
#   The 8f5090e security rationale (debuggable=true → adb run-as reads the PIN-encrypted church key in ~30s;
#   a silently-regenerated debug key can forge steward updates) is REAL and applies the moment anyone real is on it.
npx cap copy android
# WebView debugging is now controlled by the Gradle BUILD VARIANT via BuildConfig.WEB_DEBUG:
#   assembleDebug   → WEB_DEBUG=true  (dev builds, CDP diagnosis via USB)
#   assembleRelease → WEB_DEBUG=false (pilot/go-live, CDP locked out)
# MainActivity overrides setWebContentsDebuggingEnabled() at runtime. TRINITY_DEBUG=0 is no longer needed.
# GO-LIVE 2026-10-28 (owner's call: pilot users install the real signed build): release-signed with the stable
# key + non-debuggable, so no adb run-as can read the church key and every later update installs over the last.
[ -f android/app/keystore.properties ] || { echo "ERROR: keystore.properties missing — cannot release-sign" >&2; exit 1; }
( cd android && ./gradlew assembleRelease -q )
cp android/app/build/outputs/apk/release/app-release.apk "$OUT"
"$(ls -d "$ANDROID_HOME"/build-tools/* | sort -V | tail -1)/aapt2" dump badging "$OUT" | grep -q application-debuggable && { echo "DEBUGGABLE — refusing to ship" >&2; exit 1; }
echo "→ $OUT ($(du -h "$OUT" | cut -f1))  [RELEASE-signed, non-debuggable — go-live 2026-10-28]"
# restore() runs on EXIT
